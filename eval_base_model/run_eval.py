def run_single_eval(
    script_path: str,
    args: argparse.Namespace,
    script_dir: str,
) -> Tuple[str, bool, Optional[Dict], float]:
    """
    Run a single evaluation script.

    Args:
        script_path: Path to the evaluation script
        args: Parsed command-line arguments
        script_dir: Directory containing evaluation scripts

    Returns:
        Tuple of (script_name, success, results_dict, duration_seconds)
    """
    script_name = os.path.basename(script_path)
    full_path = os.path.join(script_dir, script_path)

    if not os.path.exists(full_path):
        print(f"⚠️  Script not found: {script_path}")
        return script_name, False, None, 0.0

    # Build command
    cmd = [sys.executable, full_path]

    # Add common arguments
    if args.model:
        cmd.extend(["--model", args.model])
    if args.base_url:
        cmd.extend(["--base-url", args.base_url])
    if args.max_workers is not None:
        cmd.extend(["--max-workers", str(args.max_workers)])
    if args.shot_num is not None:
        cmd.extend(["--shot-num", str(args.shot_num)])
    if args.max_samples is not None:
        cmd.extend(["--max-samples", str(args.max_samples)])
    if args.seed is not None:
        cmd.extend(["--seed", str(args.seed)])

    # Add script-specific arguments if provided
    if args.extra_args:
        cmd.extend(args.extra_args)

    print(f"\n{'='*70}")
    print(f"Running: {script_name}")
    print(f"Command: {' '.join(cmd)}")
    print(f"{'='*70}")

    start_time = time.time()
    try:
        result = subprocess.run(
            cmd,
            cwd=script_dir,
            capture_output=not args.verbose,
            text=True,
            timeout=args.timeout if args.timeout else None,
        )
        duration = time.time() - start_time

        success = result.returncode == 0

        if not args.verbose:
            if result.stdout:
                print(result.stdout)
            if result.stderr:
                print(result.stderr, file=sys.stderr)

        # Try to parse results from log file
        results_dict = None
        if success:
            results_dict = extract_results_from_logs(script_path, args)

        status = "✓" if success else "✗"
        print(f"\n{status} {script_name} completed in {duration:.1f}s (exit code: {result.returncode})")

        return script_name, success, results_dict, duration

    except subprocess.TimeoutExpired:
        duration = time.time() - start_time
        print(f"\n✗ {script_name} timed out after {duration:.1f}s")
        return script_name, False, None, duration

    except Exception as e:
        duration = time.time() - start_time
        print(f"\n✗ {script_name} failed with error: {e}")
        return script_name, False, None, duration


def extract_results_from_logs(script_path: str, args: argparse.Namespace) -> Optional[Dict]:
    """
    Extract results from the log file generated by an evaluation script.

    Args:
        script_path: Name of the evaluation script
        args: Command-line arguments containing model name

    Returns:
        Dictionary containing evaluation results, or None if not found
    """
    script_name = os.path.basename(script_path).replace("eval_", "").replace(".py", "")

    # Determine log file path
    log_dir = Path(__file__).parent / "logs" / args.model
    if not log_dir.exists():
        return None

    # Look for matching log files (handle different shot configurations)
    shot_suffix = f"{args.shot_num}shot" if args.shot_num is not None else "*shot"
    sample_suffix = f"_{args.max_samples}samples" if args.max_samples else ""

    pattern = f"{script_name}_{shot_suffix}{sample_suffix}.json"
    log_files = list(log_dir.glob(pattern))

    if not log_files:
        # Try without sample suffix
        pattern = f"{script_name}_{shot_suffix}.json"
        log_files = list(log_dir.glob(pattern))

    if not log_files:
        return None

    # Use the most recent log file
    log_file = max(log_files, key=lambda p: p.stat().st_mtime)

    try:
        with open(log_file, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        print(f"⚠️  Failed to parse log file {log_file}: {e}")
        return None


def aggregate_results(
    eval_results: List[Tuple[str, bool, Optional[Dict], float]],
    args: argparse.Namespace,
    total_duration: float,
) -> Dict:
    """
    Aggregate results from multiple evaluations.

    Args:
        eval_results: List of (script_name, success, results_dict, duration) tuples
        args: Command-line arguments
        total_duration: Total execution time

    Returns:
        Dictionary containing aggregated results
    """
    summary = {
        "subset": args.subset,
        "model": args.model,
        "timestamp": datetime.now().isoformat(),
        "total_duration_seconds": total_duration,
        "configuration": {
            "shot_num": args.shot_num,
            "max_samples": args.max_samples,
            "seed": args.seed,
            "max_workers": args.max_workers,
        },
        "evaluations": [],
        "summary_statistics": {
            "total_evaluations": len(eval_results),
            "successful": sum(1 for _, success, _, _ in eval_results if success),
            "failed": sum(1 for _, success, _, _ in eval_results if not success),
        },
    }

    total_accuracy = 0
    valid_accuracy_count = 0

    for script_name, success, results_dict, duration in eval_results:
        eval_entry = {
            "script": script_name,
            "success": success,
            "duration_seconds": duration,
        }

        if results_dict:
            eval_entry["accuracy"] = results_dict.get("accuracy", 0.0)
            eval_entry["correct"] = results_dict.get("correct", 0)
            eval_entry["total"] = results_dict.get("total", 0)

            if "accuracy" in results_dict:
                total_accuracy += results_dict["accuracy"]
                valid_accuracy_count += 1

        summary["evaluations"].append(eval_entry)

    if valid_accuracy_count > 0:
        summary["summary_statistics"]["average_accuracy"] = total_accuracy / valid_accuracy_count

    return summary


def print_summary(summary: Dict) -> None:
    """Print a formatted summary of evaluation results."""
    print("\n" + "=" * 70)
    print("EVALUATION SUMMARY")
    print("=" * 70)
    print(f"Subset: {summary['subset']}")
    print(f"Model: {summary['model']}")
    print(f"Total Duration: {summary['total_duration_seconds']:.1f}s")
    print(f"\nConfiguration:")
    print(f"  Shot: {summary['configuration']['shot_num']}")
    print(f"  Max Samples: {summary['configuration']['max_samples']}")
    print(f"  Seed: {summary['configuration']['seed']}")
    print(f"\nResults:")
    print(f"  Total Evaluations: {summary['summary_statistics']['total_evaluations']}")
    print(f"  Successful: {summary['summary_statistics']['successful']}")
    print(f"  Failed: {summary['summary_statistics']['failed']}")

    if "average_accuracy" in summary["summary_statistics"]:
        print(f"  Average Accuracy: {summary['summary_statistics']['average_accuracy']:.2f}%")

    print(f"\nPer-Evaluation Results:")
    print(f"{'Script':<30} {'Status':<10} {'Accuracy':<12} {'Duration':<10}")
    print("-" * 70)

    for eval_entry in summary["evaluations"]:
        script = eval_entry["script"]
        status = "✓ Success" if eval_entry["success"] else "✗ Failed"
        accuracy = f"{eval_entry.get('accuracy', 0):.2f}%" if "accuracy" in eval_entry else "N/A"
        duration = f"{eval_entry['duration_seconds']:.1f}s"
        print(f"{script:<30} {status:<10} {accuracy:<12} {duration:<10}")

    print("=" * 70)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Unified evaluation runner for multiple benchmark subsets",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=f"""
Available subsets:
  {', '.join(EVAL_SUBSETS.keys())}

Example usage:
  # Run all English evaluations with 5-shot
  python run_eval.py --subset english --model my-model --base-url http://localhost:8000/v1 --shot-num 5

  # Quick test with 100 samples
  python run_eval.py --subset english --model my-model --base-url http://api --max-samples 100 --shot-num 3

  # Parallel execution
  python run_eval.py --subset english --model my-model --base-url http://api --parallel --max-parallel 4
""",
    )

    # Required arguments
    parser.add_argument(
        "--subset",
        type=str,
        required=True,
        choices=list(EVAL_SUBSETS.keys()),
        help="Evaluation subset to run",
    )

    # Model configuration (forwarded to eval scripts)
    parser.add_argument(
        "--model",
        type=str,
        default=os.environ.get("EVAL_MODEL_NAME"),
        help="Model name (default: from EVAL_MODEL_NAME env var)",
    )
    parser.add_argument(
        "--base-url",
        type=str,
        default=os.environ.get("EVAL_BASE_URL"),
        help="API base URL (default: from EVAL_BASE_URL env var)",
    )

    # Evaluation configuration (forwarded to eval scripts)
    parser.add_argument(
        "--max-workers",
        type=int,
        default=None,
        help="Maximum number of concurrent workers (default: script-specific)",
    )
    parser.add_argument(
        "--shot-num",
        type=int,
        default=5,
        help="Number of few-shot examples (default: 5)",
    )
    parser.add_argument(
        "--max-samples",
        type=int,
        default=None,
        help="Random sample size for quick testing (default: None, evaluate all)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for sampling (default: 42)",
    )

    # Execution control
    parser.add_argument(
        "--parallel",
        action="store_true",
        help="Run evaluations in parallel (default: sequential)",
    )
    parser.add_argument(
        "--max-parallel",
        type=int,
        default=4,
        help="Maximum number of parallel evaluations (default: 4)",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=None,
        help="Timeout per evaluation in seconds (default: None)",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Show live output from evaluation scripts (default: False)",
    )

    # Output configuration
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory for aggregated results (default: logs/{model}/)",
    )
    parser.add_argument(
        "--no-summary",
        action="store_true",
        help="Skip saving aggregated summary file (default: False)",
    )

    # Script-specific arguments (passed through)
    parser.add_argument(
        "extra_args",
        nargs=argparse.REMAINDER,
        help="Additional arguments to pass to evaluation scripts",
    )

    args = parser.parse_args()

    # Validate required arguments
    if not args.model:
        parser.error("--model is required (or set EVAL_MODEL_NAME environment variable)")
    if not args.base_url:
        parser.error("--base-url is required (or set EVAL_BASE_URL environment variable)")

    # Get evaluation scripts for the specified subset
    eval_scripts = EVAL_SUBSETS[args.subset]
    script_dir = os.path.dirname(os.path.abspath(__file__))

    print(f"\n{'='*70}")
    print(f"UNIFIED EVALUATION RUNNER")
    print(f"{'='*70}")
    print(f"Subset: {args.subset}")
    print(f"Model: {args.model}")
    print(f"Scripts to run: {len(eval_scripts)}")
    print(f"Execution mode: {'Parallel' if args.parallel else 'Sequential'}")
    if args.parallel:
        print(f"Max parallel: {args.max_parallel}")
    print(f"{'='*70}")

    # Run evaluations
    start_time = time.time()
    eval_results = []

    if args.parallel:
        # Parallel execution
        with ProcessPoolExecutor(max_workers=args.max_parallel) as executor:
            futures = {
                executor.submit(run_single_eval, script, args, script_dir): script
                for script in eval_scripts
            }

            for future in as_completed(futures):
                result = future.result()
                eval_results.append(result)
    else:
        # Sequential execution
        for script in eval_scripts:
            result = run_single_eval(script, args, script_dir)
            eval_results.append(result)

    total_duration = time.time() - start_time

    # Aggregate and print results
    summary = aggregate_results(eval_results, args, total_duration)
    print_summary(summary)

    # Save aggregated results
    if not args.no_summary:
        output_dir = args.output_dir
        if not output_dir:
            output_dir = os.path.join(script_dir, "logs", args.model)
        os.makedirs(output_dir, exist_ok=True)

        shot_desc = f"{args.shot_num}shot" if args.shot_num > 0 else "0shot"
        sample_desc = f"_{args.max_samples}samples" if args.max_samples else ""
        output_filename = f"summary_{args.subset}_{shot_desc}{sample_desc}.json"
        output_path = os.path.join(output_dir, output_filename)

        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2, ensure_ascii=False)

        print(f"\nAggregated results saved to: {output_path}")

    # Exit with error if any evaluation failed
    failed_count = summary["summary_statistics"]["failed"]
    if failed_count > 0:
        print(f"\n⚠️  {failed_count} evaluation(s) failed")
        sys.exit(1)
    else:
        print(f"\n✓ All evaluations completed successfully")
        sys.exit(0)


if __name__ == "__main__":
    main()
